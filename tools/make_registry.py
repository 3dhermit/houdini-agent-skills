"""Generate SKILL_REGISTRY.md from the skills' own meta.json files.

The catalog is generated, not hand-written, so it cannot drift from reality.
Run from the repo root:  python tools/make_registry.py
CI runs it and fails if the committed file differs (see .github/workflows/ci.yml).
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from houdini_skills.registry import discover  # noqa: E402

HEADER = """# SKILL_REGISTRY

Every integrated skill, generated by `tools/make_registry.py` from each skill's
`meta.json`. **Do not hand-edit** - edit the metadata and regenerate.

Verified build: **Houdini 22.0.368 (Windows)**. Other versions in a skill's
`houdini_versions` are a declared floor, not a tested one.
"""


def main() -> int:
    skills = discover()
    if not skills:
        print("no skills found", file=sys.stderr)
        return 1
    lines = [HEADER, ""]
    lines.append("| skill | category | version | Houdini | actions | verified on |")
    lines.append("|---|---|---|---|---|---|")
    for name in sorted(skills):
        spec = skills[name]
        m = spec.meta
        lines.append(
            f"| `{name}` | `{spec.category}` | {m.get('version','?')} | "
            f"{', '.join(m.get('houdini_versions', []))} | "
            f"{', '.join(sorted(m.get('actions', {})))} | "
            f"{', '.join(m.get('verified_on', [])) or 'never'} |"
        )
    lines.append("")

    for name in sorted(skills):
        spec = skills[name]
        m = spec.meta
        lines.append(f"## {name}")
        lines.append("")
        lines.append(m.get("description", "").strip())
        lines.append("")
        if m.get("triggers"):
            lines.append("**Trigger prompts that should select this skill**")
            for t in m["triggers"]:
                lines.append('- "' + t + '"')
            lines.append("")
        if m.get("actions"):
            lines.append("**Actions** (payload schema lives in "
                         f"`skills/{spec.category}/meta.json`)")
            for action in sorted(m["actions"]):
                schema = m["actions"][action]
                req = schema.get("required", [])
                props = sorted(schema.get("properties", {}))
                lines.append(f"- `{action}` - required: {', '.join(req) or 'none'}; "
                             f"optional: {', '.join(p for p in props if p not in req) or 'none'}")
            lines.append("")
        if m.get("examples"):
            lines.append("**Examples**")
            lines.append("```bash")
            lines.extend(m["examples"])
            lines.append("```")
            lines.append("")
        if m.get("sources"):
            lines.append("**Curation sources** (what each contributed is stated explicitly;")
            lines.append("anything marked 'NOTHING' was consulted but not merged)")
            for src in m["sources"]:
                lines.append(f"- <{src.get('repo','')}> - licence: {src.get('license','?')} - "
                             f"{src.get('used_for','')}")
            lines.append("")
    lines.append("## Known limitations (v2.0.0)")
    lines.append("")
    lines.append("- Verified only on 22.0.368; the 19.5-21.x floor is declared, not tested.")
    lines.append("- `simulation-tools` does not author DOP graph contents and never steps a sim.")
    lines.append("- `rendering` never renders; Karma AOV authoring is out of scope.")
    lines.append("- `usd-pipeline` proves one file landed; layer stacks / MaterialX are out of scope.")
    lines.append("- Karma requires H20+, so the 19.5 floor gets an explicit `engine_unavailable` error.")
    lines.append("- Voxel *values* cannot be read back on this build: no verified `hou.Volume` "
                  "field accessor exists (`fieldNames` / `volumePrimitive` / `volumefields` all "
                  "raise), so the pyro recipe reports them under `not_verified` instead of "
                  "claiming a verification it cannot do.")
    lines.append("- `usd-pipeline.sopimport` can bind the LOP's `primpath` parm but cannot move "
                  "the authored prims with it on 22.0.368; the payload says so beside the stage "
                  "paths it actually read.")
    lines.append("- `vex-helper.lint` is a pre-filter, not a validator: its verified-call list is "
                  "not Houdini's builtin set, and a clean lint never certifies that VEX compiles.")
    lines.append("")
    lines.append("## Migrating from v1.0.0 (MAJOR)")
    lines.append("")
    lines.append("Knob changes, generated by comparing each `meta.json` against the `v1.0.0` tag:")
    lines.append("")
    lines.append("| action | removed | added |")
    lines.append("|---|---|---|")
    lines.append("| `simulation-tools.pyro` | `cache_dir`, `resolution_scale` | `source_radius`, "
                  "`voxel_size`, `density` |")
    lines.append("| `simulation-tools.flip` | - | `site_count` |")
    lines.append("| `rendering.configure` | `path` (bound nothing; the ROP has 405 parms and no "
                  "such name) | `camera` |")
    lines.append("| `usd-pipeline.export` | `unpack` (no parm read it) | `default_prim`, "
                  "`flatten_sop_layers`, `keep_layers_together` |")
    lines.append("| `usd-pipeline.sopimport` | `prim_path` schema default `/world/asm` (a silent "
                  "binding that provably does not move prims) | - |")
    lines.append("| `vex-helper.validate` | - | `node_type` (`attribwrangle` / `volumewrangle`) |")
    lines.append("")
    lines.append("Result envelopes grew read-back keys. Treat what Houdini reports, not what was "
                  "requested:")
    lines.append("")
    lines.append("- `rendering.configure`: `applied[knob]` is now `{parm, requested, kept, eval}`; "
                  "new `drift`, `drift_note`, `cleared_keyframes` (`f1`/`f2` arrive channelled as "
                  "`$FSTART`/`$FEND`, and a plain `set()` on them is a silent no-op until the "
                  "channels are deleted).")
    lines.append("- `simulation-tools.pyro`: `parm_report` per knob, `solver_wiring`, "
                  "`source_stats`, `not_verified`. The old `pyrosource` + density-wrangle recipe "
                  "was a lie - that node has no `snippet` parm.")
    lines.append("- `usd-pipeline.sopimport`: `prim_path` is replaced by `prim_path_requested`, "
                  "`prim_path_kept`, `prim_path_parm`, plus `stage_prim_paths`, "
                  "`stage_prim_stats` and a note when the two disagree.")
    lines.append("- `sop-automation.set_parms`: entries carry `kept` and the call reports `drift`; "
                  "for menu parms `rawValue()` is the label and `eval()` is the index.")
    lines.append("- `sop-automation.geo_stats` and the sim builders: `prim_types` (a FLIP source "
                  "reports `Volume: 1, PolyLine: 2582` - a prim count alone hid that).")
    lines.append("- `vex-helper.list_templates` / `template`: each carries `node_type`, "
                  "`wrangle_kind` and a `binding_note`; `explain` line entries gained a `note`.")
    lines.append("- Failures: `SkillFailure.__str__` now includes the hint and source, so a "
                  "refusal that carried 'closest: polyextrude, ...' suggestions actually shows "
                  "them (agents usually print the exception, not `to_result()`).")
    lines.append("")
    text = "\n".join(lines) + "\n"
    out = os.path.join(ROOT, "SKILL_REGISTRY.md")
    check = "--check" in sys.argv
    if check:
        current = open(out, encoding="utf-8").read() if os.path.isfile(out) else ""
        if current != text:
            print("SKILL_REGISTRY.md is out of date - run python tools/make_registry.py",
                  file=sys.stderr)
            return 1
        print("SKILL_REGISTRY.md is current")
        return 0
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote SKILL_REGISTRY.md ({len(skills)} skills, {len(text)} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
